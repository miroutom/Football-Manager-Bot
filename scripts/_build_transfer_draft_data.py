def _load_v1_rows() -> list[Row]:
    if not _V1_PATH.exists():
        import subprocess

        try:
            blob = subprocess.check_output(
                ["git", "show", "883c939:data/transfer_window_draft.json"],
                cwd=_ROOT,
                text=True,
            )
            _V1_PATH.write_text(blob, encoding="utf-8")
        except (subprocess.CalledProcessError, OSError):
            return []
    raw = json.loads(_V1_PATH.read_text(encoding="utf-8"))
    rows: list[Row] = []
    for m in raw.get("moves") or []:
        if m.get("position") == "ВРТ":
            continue
        rows.append(
            (
                m["player"],
                m["position"],
                int(m["overall"]),
                m["from_team"],
                m["to_team"],
                str(m.get("note") or ""),
            )
        )
    return rows


def _merge_rows(*sources: list[Row]) -> list[Row]:
    """Поздние источники перекрывают ранние по ключу (игрок, позиция)."""
    by_key: dict[tuple[str, str], Row] = {}
    for src in sources:
        for row in src:
            key = (row[0].strip().lower(), row[1].strip().upper())
            by_key[key] = row
    return list(by_key.values())


def _counts(rows: list[Row]) -> tuple[dict[str, int], dict[str, int]]:
    out: dict[str, int] = defaultdict(int)
    inn: dict[str, int] = defaultdict(int)
    for _, _, _, fr, to, _ in rows:
        out[fr] += 1
        inn[to] += 1
    return out, inn


def _trim_surplus(rows: list[Row], teams: set[str]) -> list[Row]:
    """Убирает лишние переходы (сначала слабые по OVR)."""
    result = list(rows)

    def ok() -> bool:
        out, inn = _counts(result)
        return all(out.get(t, 0) <= 5 and inn.get(t, 0) <= 5 for t in teams)

    while not ok():
        out, inn = _counts(result)
        candidates: list[tuple[int, int]] = []
        for i, row in enumerate(result):
            fr, to, ovr = row[3], row[4], row[2]
            if out.get(fr, 0) > 5 or inn.get(to, 0) > 5:
                candidates.append((ovr, i))
        if not candidates:
            break
        _, idx = min(candidates)
        result.pop(idx)
    return result


def _solve_balance(rows: list[Row], teams: set[str], pool: list[Row]) -> list[Row]:
    result = _trim_surplus(rows, teams)
    used = {(r[0].lower(), r[1].upper()) for r in result}

    for _ in range(800):
        out, inn = _counts(result)
        if len(result) == 200 and all(
            out.get(t, 0) == 5 and inn.get(t, 0) == 5 for t in teams
        ):
            return result

        need_out = {t: max(0, 5 - out.get(t, 0)) for t in teams}
        need_in = {t: max(0, 5 - inn.get(t, 0)) for t in teams}
        surplus_out = {t: max(0, out.get(t, 0) - 5) for t in teams}
        surplus_in = {t: max(0, inn.get(t, 0) - 5) for t in teams}

        if sum(surplus_out.values()) + sum(surplus_in.values()) > 0:
            result = _trim_surplus(result, teams)
            continue

        if len(result) > 200:
            # убрать один из самых слабых, не создавая новый перебор
            weakest = min(
                range(len(result)),
                key=lambda i: (
                    result[i][2],
                    -need_out.get(result[i][3], 0),
                    -need_in.get(result[i][4], 0),
                ),
            )
            result.pop(weakest)
            continue

        added = False
        for row in pool:
            key = (row[0].lower(), row[1].upper())
            if key in used:
                continue
            fr, to = row[3], row[4]
            if fr not in teams or to not in teams:
                continue
            if out.get(fr, 0) >= 5 or inn.get(to, 0) >= 5:
                if need_out.get(fr, 0) <= 0 or need_in.get(to, 0) <= 0:
                    continue
            result.append(row)
            used.add(key)
            added = True
            break

        if not added:
            break

    return result


def build_rows() -> list[Row]:
    from utils.transfer_advice import all_league_teams
    from utils.transfer_market_draft import _EXCLUDED_TEAMS

    teams = set(all_league_teams()) - _EXCLUDED_TEAMS
    merged = _merge_rows(_load_v1_rows(), _DEPTH_FILLERS, CURATED, MANDATORY)
    pool = _merge_rows(_DEPTH_FILLERS, CURATED, MANDATORY)
    balanced = _solve_balance(merged, teams, pool)
    return balanced


