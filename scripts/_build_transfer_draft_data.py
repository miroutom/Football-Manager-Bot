def main() -> int:
    from collections import defaultdict

    from utils.transfer_market_draft import validate_draft, DraftMove

    moves = [
        DraftMove(p, pos, ovr, fr, to, note)
        for p, pos, ovr, fr, to, note in _RAW
    ]
    out = defaultdict(int)
    inn = defaultdict(int)
    for m in moves:
        out[m.from_team] += 1
        inn[m.to_team] += 1

    print(f"Total moves: {len(moves)}")
    bad = [(t, out[t], inn[t]) for t in sorted(set(out) | set(inn), key=str.lower) if out[t] != 5 or inn[t] != 5]
    for t, o, i in bad:
        print(f"  {t}: OUT {o} IN {i}")

    errs, warns = validate_draft(moves)
    print(f"Validator errors: {len(errs)}, GK warnings: {len(warns)}")
    for e in errs[:25]:
        print(f"  {e}")

    payload = {
        "version": 1,
        "status": "draft_review",
        "description": "Черновик трансферного окна (оценка, без применения в БД).",
        "moves": [m.as_dict() for m in moves],
    }
    path = _ROOT / "data" / "transfer_window_draft.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {path}")
    return 1 if errs else 0


